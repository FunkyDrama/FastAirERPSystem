import random
import string
import datetime as dt
from typing import Iterable


RNG = random.Random()


def pick(seq: Iterable[str]) -> str:
    """
    Randomly selects an item from the given iterable sequence of strings. The sequence is internally converted to a list,
    and an item is picked based on a random index generated within the bounds of its length.

    :param seq: An iterable sequence of strings from which a random string is selected.
    :type seq: Iterable[str]
    :return: A randomly selected string from the supplied sequence.
    :rtype: str
    """
    seq = list(seq)
    return seq[RNG.randrange(0, len(seq))]


